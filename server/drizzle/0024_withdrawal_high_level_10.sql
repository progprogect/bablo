-- Порог «высокого уровня» для вывода опущен с 22 до 10 (просьба пользователя от
-- 23.10.2026): на 22-м уровне 3R начинались так поздно, что правило фактически не
-- работало. Пересчитываем ещё НЕ выполненные требования, чтобы они не остались со старой
-- суммой, — ровно как это уже делала миграция 0017_withdrawal_multiplier.sql при смене
-- множителя. История сделанных выводов (withdrawn_at IS NOT NULL) не трогается: там
-- записан факт, а не план.
--
-- Запрос приводит каждое невыполненное требование к ТЕКУЩЕМУ правилу целиком, а не
-- правит только диапазон 10–21: так результат не зависит от того, каким множителем строка
-- была посчитана при создании.
UPDATE "level_withdrawals" AS lw
SET "required_usd" = rl."risk_usd" * (CASE WHEN lw."level" >= 10 THEN 3 ELSE 2 END)
FROM "risk_levels" AS rl
WHERE rl."level" = lw."level" AND lw."withdrawn_at" IS NULL;
