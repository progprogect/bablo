-- Стартовая статистика по часам (просьба пользователя от 02.11.2026).
--
-- После потери базы на Railway история сделок не восстановилась, но пользователь помнит
-- свою статистику по часам и хочет, чтобы гистограмма «Тейки по часам открытия»
-- продолжила счёт с неё, а не с нуля.
--
-- Отдельная таблица, а НЕ выдуманные сделки в trades: синтетические сделки испортили бы
-- месячную статистику, суммы R, прогресс уровней и список сделок. Здесь же цифры живут
-- отдельным слоем и складываются только в гистограмме часов.
CREATE TABLE IF NOT EXISTS "hour_baseline" (
  "hour" integer PRIMARY KEY,
  "total" integer NOT NULL,
  "tp_count" integer NOT NULL,
  "updated_at" timestamp with time zone DEFAULT now() NOT NULL
);
